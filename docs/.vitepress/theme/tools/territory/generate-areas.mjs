#!/usr/bin/env node
// Builds areas.ts, the territory tool's list of conquerable areas.
//
//   node docs/.vitepress/theme/tools/territory/generate-areas.mjs [path/to/mud]
//
// The MUD checkout defaults to $AU_MUD_DIR, then ~/Sites/adventuresunlimited-code.
// It reads area/area.lst for the areas the game loads and each area file's
// #AREADATA header: Name is what `territory clan` prints, Conquer 1 marks an
// area a clan can take. Each area is then matched to its row in
// docs/world/areas.md, which gives the level range, the name the docs use and
// the anchor to link to. A level in the area file's Credits that disagrees with
// areas.md stops the script, so the two can't drift apart unnoticed.

import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const mudDir = process.argv[2] ?? process.env.AU_MUD_DIR ?? join(homedir(), 'Sites/adventuresunlimited-code');
const areasMd = join(here, '../../../../world/areas.md');
const outFile = join(here, 'areas.ts');

// Names the docs spell differently, where neither the area's Name nor the
// name in its Credits finds the row. Area file name -> areas.md name.
const aliases = {};

/** The anchor rule areas.md follows for most rows. */
const slug = name =>
  name
    .toLowerCase()
    .replace(/^the\s+/, '')
    .replace(/'/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

/** "1-20" -> { min: 1, max: 20 }; ALL and HERO get a range for filtering. */
function parseLevel(label) {
  if (label === 'ALL') return { label, min: 0, max: 110 };
  if (label === 'HERO') return { label, min: 100, max: 110 };
  const match = /^(\d+)(?:-(\d+))?$/.exec(label);

  if (!match) return null;
  const min = Number(match[1]);
  const max = Number(match[2] ?? match[1]);

  return { label: min === max ? String(min) : `${min}-${max}`, min, max };
}

// Rows of the areas table: | Level | <a id="x"></a>Name or [Name](url) | ...
const docRows = new Map();

for (const line of readFileSync(areasMd, 'utf8').split('\n')) {
  const match = /^\| ([^|]+) \| <a id="([^"]+)"><\/a>(.+?) \|/.exec(line);

  if (!match) continue;
  const [, level, anchor, cell] = match;
  const name = cell.replace(/^\[(.+?)\]\(.*\)$/, '$1').trim();

  docRows.set(slug(name), { name, anchor, level: level.trim() });
}

const listed = readFileSync(join(mudDir, 'area/area.lst'), 'utf8')
  .split(/\r?\n/)
  .map(line => line.trim())
  .filter(Boolean);
const files = listed.slice(0, listed.indexOf('$') === -1 ? undefined : listed.indexOf('$'));

const areas = [];
const problems = [];

for (const file of files) {
  const text = readFileSync(join(mudDir, 'area', file), 'latin1');

  if (!text.startsWith('#AREADATA')) continue;
  const header = text.slice(0, text.search(/^End\s*$/m));
  const field = key => new RegExp(`^${key} (.*)$`, 'm').exec(header)?.[1];

  if (Number(field('Conquer')) !== 1) continue;
  const name = field('Name').replace(/~$/, '').trim();
  const credits = /^\{\s*([^}]*?)\s*\}\s*\S+\s+(.*?)\s*~?$/.exec(field('Credits') ?? '');
  const creditsLevel = credits ? parseLevel(credits[1].replace(/\s+/g, '-')) : null;
  const creditsName = credits?.[2].trim();
  const row =
    docRows.get(slug(aliases[name] ?? name)) ?? (creditsName ? docRows.get(slug(creditsName)) : undefined);

  if (!row) {
    problems.push(`${file}: "${name}" has no row in areas.md (add it, or an alias here)`);
    continue;
  }
  const level = parseLevel(row.level);

  if (!level) {
    problems.push(`${file}: areas.md level "${row.level}" for ${row.name} isn't a range`);
    continue;
  }
  if (!creditsLevel) {
    problems.push(`${file}: can't read a level from its Credits line`);
  } else if (creditsLevel.label !== level.label) {
    problems.push(`${file}: Credits say ${creditsLevel.label}, areas.md says ${level.label} for ${row.name}`);
  }
  areas.push({ name, docName: row.name, anchor: row.anchor, ...level });
}

if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}

const quote = text => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const body = areas
  .map(area => {
    const fields = Object.entries(area).map(([key, value]) =>
      `${key}: ${typeof value === 'number' ? value : quote(value)}`
    );

    return `  { ${fields.join(', ')} },`;
  })
  .join('\n');

writeFileSync(
  outFile,
  `// Generated by generate-areas.mjs from the MUD's area files and
// docs/world/areas.md. Don't edit by hand: rerun the script.
//
// Every area a clan can conquer (Conquer 1 in its #AREADATA header), in the
// order the game loads them, which is the order \`territory\` lists them in.
// name is what the game prints; docName, anchor and the level come from the
// area's row in areas.md. ALL is any level (0-110), HERO is 100-110.

export interface TerritoryArea {
  name: string;
  docName: string;
  anchor: string;
  label: string;
  min: number;
  max: number;
}

export const territoryAreas: TerritoryArea[] = [
${body}
];
`
);
console.log(`Wrote ${areas.length} areas to ${outFile}`);
